export const getFounder = (slug: string): Founder => {
  const f = founders.find((x) => x.slug === slug);
  if (!f) throw new Error("Unknown founder: " + slug);
  return f;
};

export const initialsOf = (name: string): string =>
  name
    .split(" ")
    .filter(Boolean)
    .slice(0, 2)
    .map((w) => w[0])
    .join("")
    .toUpperCase();
